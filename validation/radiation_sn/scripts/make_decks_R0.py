#!/usr/bin/env python
"""R0: consolidate the earlier Sn gates (athenapk/runs/sn_*, SN_TRANSPORT_DESIGN Sec. 6/12/13 + RAD_ACCURACY_ITEMS)
into this module and re-run them on the current binary.

For every gate two deck families are written to inputs/R0/:
  <gate>_orig.in   the archived deck VERBATIM (+ the per-family scheme keys its submit script passed on the CLI)
  <gate>_prod.in   the same deck + rad_common.PROD_RAD (production Sn solver keys) + PROD_HYDRO_DUAL
Arms keep the original CLI overrides (none contains a comma). Every R0 box is PERIODIC, so sn_bc_incoming = planck is
inert here (it is exercised in R2/R3).

Changes forced by the code since the gates were run (2026-09-06..14), each stated:
  * G8 arm_m1er (the retired sn_source = m1er) cannot run: radiation_sn.cpp l.101 accepts only "planck". Its role,
    a falsification arm that must NOT reach a_R T^4, is taken by arm_noabs (kappa_a_code = 0: no emission, no
    absorption, Er must stay at the initial 1e-30).
  * sn_restart_fix legs started from an M1 restart (transport = m1 removed in 117e2fe8). Replaced by a pure-Sn
    two-leg vs continuous test, scripts/r0_restart.sh.
  * fleck5 stiff_* and ray4 intermediate ordinate arms are not re-run (R1 and R5 cover them).
writes: inputs/R0/*.in, inputs/R0_runs.txt (rundir | deck | overrides | nranks)
"""
import os
import shutil

from rad_common import INP, OLD, MOD, prod_overlay, set_keys, fmt

D = os.path.join(INP, "R0")
os.makedirs(D, exist_ok=True)
CHK = os.path.join(MOD, "scripts", "r0_checkers")
os.makedirs(CHK, exist_ok=True)

VOP = {"sn_verify_operator": "true"}
STEP = {"sn_spatial": "step"}
SOU = {"sn_spatial": "sou", "sn_sou_kappa": "1.0", "sn_sou_linear_prolong": "true"}
SEAM_COMMON = {"sn_solver": "bicgstab", "sn_smoother": "ordered", "sn_verify_operator": "true"}


def write(name, text, src):
    p = os.path.join(D, name)
    hdr = f"# R0 deck generated by scripts/make_decks_R0.py from {src}\n"
    open(p, "w").write(hdr + text)
    return name


def fam(gate, src, families):
    """families: {family: dict of <radiation> keys or 'prod'} -> {family: deck name}"""
    base = open(src).read()
    out = {}
    for f, keys in families.items():
        t = prod_overlay(base) if keys == "prod" else (set_keys(base, "radiation", keys, f"R0 {f} family")
                                                       if keys else base)
        out[f] = write(f"{gate}_{f}.in", t, src)
    return out


runs = []


def add(gate, decks, arms, nranks):
    for f, deck in decks.items():
        for a, ov in arms.items():
            runs.append(f"R0/{gate}/{f}/arm_{a} | R0/{deck} | {ov} | {nranks}")


# ---- G8-G11: unit calibration, coupling, scattering, Fleck stability (8 ranks, 16^3, 8^3 blocks)
for g, arms in [
    ("G8", {"planck": "", "t2": "problem/rad_pulse/p0=2.0 radiation/arad_code=3.0",
            "noabs": "radiation/kappa_a_code=0.0"}),
    ("G9", {"creduc1": "radiation/creduc=1.0", "creduc4": "radiation/creduc=4.0",
            "creduc1_tol12": "radiation/creduc=1.0 radiation/sn_rel_tol=1.0e-12"}),
    ("G10", {"ks0": "radiation/kappa_s_code=0.0", "ks2": "radiation/kappa_s_code=2.0"}),
    ("G11", {"alpha1": "radiation/sn_fleck_alpha=1.0", "alpha0": "radiation/sn_fleck_alpha=0.0"}),
]:
    src = f"{OLD}/sn_{g.lower()}/deck.in"
    add(g, fam(g, src, {"orig": None, "prod": "prod"}), arms, 8)
    shutil.copy(f"{OLD}/sn_{g.lower()}/check_{g.lower()}.py", CHK)

# ---- K1/K3/K5: BiCGSTAB == Richardson (uniform / static AMR / live scattering); step, sou, prod families
KARMS = {"ref": "radiation/sn_solver=richardson",
         "kry0": "radiation/sn_solver=bicgstab radiation/sn_precond_sweeps=0",
         "kry1": "radiation/sn_solver=bicgstab radiation/sn_precond_sweeps=1",
         "tight": "radiation/sn_solver=richardson radiation/sn_rel_tol=1.0e-13"}
for g, d, chk in [("K1", "sn_k1_sou", "check_k1.py"), ("K3", "sn_k3_sou", "check_k3.py"),
                  ("K5", "sn_k5_sou", "check_k5.py")]:
    src = f"{OLD}/{d}/deck.in"
    add(g, fam(g, src, {"step": {**VOP, **STEP}, "sou": {**VOP, **SOU}, "prod": "prod"}), KARMS, 8)
    shutil.copy(f"{OLD}/{d}/{chk}", CHK)

# ---- seam2 (accuracy #2): driven steady state, static AMR seam at the steepest gradient
SEAM_ARMS = {"amr": "", "coarse": "parthenon/mesh/refinement=none",
             "fine": "parthenon/mesh/refinement=none parthenon/mesh/nx1=32 parthenon/mesh/nx2=32 parthenon/mesh/nx3=32 "
                     "parthenon/meshblock/nx1=8 parthenon/meshblock/nx2=8 parthenon/meshblock/nx3=8"}
src = f"{OLD}/sn_seam2/deck.in"
add("SEAM", fam("SEAM", src, {"step": {**SEAM_COMMON, **STEP}, "sou": {**SEAM_COMMON, **SOU}, "prod": "prod"}),
    SEAM_ARMS, 8)
shutil.copy(f"{OLD}/sn_seam2/check_g6h.py", CHK)

# ---- fleck5 (accuracy #5): Fleck temporal order, dt = 2^-6 / N, 1 rank, 8^3
FARMS = {}
for A in ("1.0", "0.5", "0.0"):
    for N in (1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024):
        if A == "0.0" and N < 4:
            continue
        FARMS[f"a{A}_N{N}"] = f"radiation/sn_fleck_alpha={A} parthenon/time/dt_force={fmt(2.0 ** -6 / N)}"
src = f"{OLD}/sn_fleck5/deck.in"
add("FLECK", fam("FLECK", src, {"orig": None, "prod": "prod"}), FARMS, 1)
shutil.copy(f"{OLD}/sn_fleck5/check_fleck5.py", CHK)

# ---- K4: diffusion limit (deck_b, 512x8x8, scattering-dominated), tau_cell 0.2 / 0.5 / 1; 4 ranks
K4 = {"tau0p2": ("25.6", "0.030720", "0.0846", "0.003072"), "tau0p5": ("64.0", "0.076800", "0.2115", "0.007680"),
      "tau1": ("128.0", "0.153600", "0.4000", "0.015360")}
k4 = lambda ks, tl, cfl, od: (f"radiation/kappa_s_code={ks} parthenon/time/tlim={tl} parthenon/time/cfl={cfl} "
                              f"parthenon/output0/dt={od} radiation/sn_solver=bicgstab radiation/sn_verify_operator=true")
src = f"{OLD}/sn_k4_diff/deck_b.in"
dk = fam("K4", src, {"orig": None, "prod": "prod"})
for t, v in K4.items():
    runs.append(f"R0/K4/orig/f_sou1_{t} | R0/{dk['orig']} | {k4(*v)} radiation/sn_spatial=sou radiation/sn_sou_kappa=1.0 | 4")
    runs.append(f"R0/K4/orig/f_step_{t} | R0/{dk['orig']} | {k4(*v)} radiation/sn_spatial=step | 4")
    runs.append(f"R0/K4/prod/f_sou1_{t} | R0/{dk['prod']} | {k4(*v)} | 4")
for f in ("check_k4sou.py", "check_k4dd.py"):
    shutil.copy(f"{OLD}/sn_k4_diff/{f}", CHK)

# ---- ray4 (accuracy #4): ray effects around a hot cube, thin; reference = 24x48 ordinates
RARMS = {"z4p8": "radiation/sn_nzeta=4 radiation/sn_npsi=8", "z8p16": "radiation/sn_nzeta=8 radiation/sn_npsi=16",
         "z24p48": "radiation/sn_nzeta=24 radiation/sn_npsi=48",
         "z4p8sou": "radiation/sn_nzeta=4 radiation/sn_npsi=8 radiation/sn_spatial=sou"}
src = f"{OLD}/sn_ray4/deck.in"
add("RAY", fam("RAY", src, {"orig": None}), RARMS, 8)
shutil.copy(f"{OLD}/sn_ray4/check_ray4.py", CHK)

# ---- restart: pure-Sn two-leg vs continuous (scripts/r0_restart.sh), production keys
fam("RST", f"{OLD}/sn_restart_fix/deck.in", {"prod": "prod"})

open(os.path.join(INP, "R0_runs.txt"), "w").write("\n".join(runs) + "\n")
print(f"{len(runs)} runs -> inputs/R0_runs.txt; decks in inputs/R0/; checkers copied to scripts/r0_checkers/")
